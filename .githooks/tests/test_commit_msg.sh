#!/usr/bin/env bash
# Runs .githooks/commit-msg over messages it must refuse and messages it must accept.
set -uo pipefail
hook="$(cd "$(dirname "$0")/.." && pwd)/commit-msg"
tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT
failures=0

expect() {
    local want="$1" msg="$2" got
    printf '%b\n' "$msg" >"$tmp"
    if bash "$hook" "$tmp" >/dev/null 2>&1; then got=accept; else got=refuse; fi
    if [[ "$got" != "$want" ]]; then
        printf 'FAIL: expected %s, got %s for:\n%b\n\n' "$want" "$got" "$msg"
        failures=$((failures + 1))
    fi
}

expect refuse 'Fix the thing\n\nCo-Authored-By: Claude Opus <noreply@anthropic.com>'
expect refuse 'Fix the thing\n\nco-authored-by: GitHub Copilot <copilot@github.com>'
expect refuse 'Fix the thing\n\nCo-authored-by: AI Assistant <bot@example.com>'
expect refuse 'Fix the thing\n\nClaude-Session: https://claude.ai/code/session_x'
expect refuse 'Fix the thing\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)'
expect refuse 'Fix the thing\n\nGenerated by ChatGPT'
expect refuse 'Fix the thing\n\n- Drafted with Codex'

expect accept 'Fix the thing\n\nCo-Authored-By: Jane Doe <jane@example.com>'
expect accept 'Document the rule against `Co-Authored-By: Claude` trailers'
expect accept 'Fix email for Kailash\n\nDrafted by Vainnor'
expect accept 'Retry the AI-free path when the claim fails'
expect accept 'Fix the thing\n\n# Co-Authored-By: Claude (a git comment line, stripped by git)'

if [[ $failures -gt 0 ]]; then
    echo "$failures commit-msg case(s) failed"
    exit 1
fi
echo "commit-msg: all cases passed"
